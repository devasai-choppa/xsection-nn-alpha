"""Load walk-forward artifacts for the explainer scenes and the dashboard.

Paths come from the project config. Checkpoints of every epoch stay in
``checkpoints/`` (regenerated by training). A copy of each window's final
primary-seed network is also kept under ``data/processed/networks`` so the
dashboard can draw weights without the full training trajectory.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from xsnn.config import load_config
from xsnn.features import month_end
from xsnn.models.mlp import load_mlp


def artifacts(config_path: str | Path | None = None) -> dict[str, Any]:
    """Load config. ``config_path`` defaults to ``configs/default.yaml``."""
    return load_config(config_path)


def _read(path: Path) -> pd.DataFrame:
    frame = pd.read_parquet(path)
    for column in ("date", "signal_date", "realized_date"):
        if column in frame.columns:
            frame[column] = pd.to_datetime(frame[column])
    return frame


def predictions(cfg: dict[str, Any]) -> pd.DataFrame:
    return _read(Path(cfg["outputs"]["processed"]) / "predictions.parquet")


def panel(cfg: dict[str, Any]) -> pd.DataFrame:
    frame = _read(Path(cfg["outputs"]["processed"]) / "panel.parquet")
    return frame.set_index(["date", "ticker"]).sort_index()


def monthly_returns(cfg: dict[str, Any]) -> pd.DataFrame:
    return _read(Path(cfg["outputs"]["reports"]) / "monthly_returns.parquet")


def decile_returns(cfg: dict[str, Any]) -> pd.DataFrame:
    return _read(Path(cfg["outputs"]["reports"]) / "decile_returns.parquet")


def ic_series(cfg: dict[str, Any]) -> pd.DataFrame:
    return _read(Path(cfg["outputs"]["reports"]) / "ic_series.parquet")


def metrics_table(cfg: dict[str, Any]) -> pd.DataFrame:
    payload = json.loads((Path(cfg["outputs"]["reports"]) / "metrics.json").read_text(encoding="utf-8"))
    return pd.DataFrame(payload)


def universe(cfg: dict[str, Any]) -> pd.DataFrame:
    path = Path(cfg["data"]["cache_dir"]) / "universe.csv"
    if not path.exists():
        return pd.DataFrame(columns=["ticker", "name", "sector"])
    return pd.read_csv(path)


def activation_dates(cfg: dict[str, Any]) -> list[pd.Timestamp]:
    folder = Path(cfg["outputs"]["activations"])
    dates = [pd.Timestamp(path.stem) for path in folder.glob("*.npz")]
    return sorted(dates)


def load_activation(cfg: dict[str, Any], date: pd.Timestamp | str) -> dict[str, Any]:
    stamp = pd.Timestamp(date).strftime("%Y-%m-%d")
    path = Path(cfg["outputs"]["activations"]) / f"{stamp}.npz"
    if not path.exists():
        raise FileNotFoundError(f"No activation dump for {stamp}")
    with np.load(path, allow_pickle=False) as blob:
        return {key: blob[key] for key in blob.files}


def choose_explainer_date(cfg: dict[str, Any]) -> pd.Timestamp:
    """A liquid, fully observed test month used by the explainer scenes."""
    available = set(activation_dates(cfg))
    for candidate in ("2024-12-31", "2023-12-31", "2024-06-30", "2025-06-30"):
        stamp = pd.Timestamp(candidate)
        if stamp in available:
            return stamp
    if not available:
        raise FileNotFoundError("No activation dumps found. Run `make train` first.")
    return max(available)


def window_meta(cfg: dict[str, Any], date: pd.Timestamp | str) -> dict[str, Any]:
    """Training-window metadata whose test block contains ``date``."""
    target = month_end(date)
    root = Path(cfg["outputs"]["checkpoints"])
    for path in sorted(root.glob("*/meta.json")):
        meta = json.loads(path.read_text(encoding="utf-8"))
        start = month_end(meta["test_start"])
        end = month_end(meta["test_end_exclusive"])
        if start <= target < end:
            meta["checkpoint_dir"] = str(path.parent)
            return meta
    # Calendar-year windows are the default schedule even if metas were not copied.
    return {"window_id": f"{target.year:04d}-01", "checkpoint_dir": str(root / f"{target.year:04d}-01")}


def export_inference_checkpoints(cfg: dict[str, Any]) -> list[Path]:
    """Copy each window's last primary-seed epoch into the processed store."""
    dest_root = Path(cfg["outputs"]["processed"]) / "networks"
    dest_root.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    root = Path(cfg["outputs"]["checkpoints"])
    for folder in sorted(path for path in root.iterdir() if path.is_dir()):
        epochs = sorted(folder.glob("epoch_*.pt"), key=lambda path: int(path.stem.split("_")[1]))
        if not epochs:
            continue
        dest = dest_root / f"{folder.name}.pt"
        shutil.copyfile(epochs[-1], dest)
        written.append(dest)
    return written


def inference_checkpoint(cfg: dict[str, Any], window_id: str, epoch: int | None = None) -> Path:
    """Resolve a checkpoint, preferring an explicit epoch in the training tree."""
    train_dir = Path(cfg["outputs"]["checkpoints"]) / window_id
    if epoch is not None:
        path = train_dir / f"epoch_{epoch}.pt"
        if path.exists():
            return path
    if epoch is None and train_dir.exists():
        epochs = sorted(train_dir.glob("epoch_*.pt"), key=lambda path: int(path.stem.split("_")[1]))
        if epochs:
            return epochs[-1]
    exported = Path(cfg["outputs"]["processed"]) / "networks" / f"{window_id}.pt"
    if exported.exists():
        return exported
    raise FileNotFoundError(f"No checkpoint for window {window_id}")


def load_window_model(cfg: dict[str, Any], window_id: str, epoch: int | None = None):
    """Load one MLP and its checkpoint payload."""
    path = inference_checkpoint(cfg, window_id, epoch=epoch)
    return load_mlp(path)


def epoch_payloads(cfg: dict[str, Any], window_id: str) -> list[dict[str, Any]]:
    """Every saved epoch for the learning animation, in order."""
    folder = Path(cfg["outputs"]["checkpoints"]) / window_id
    paths = sorted(folder.glob("epoch_*.pt"), key=lambda path: int(path.stem.split("_")[1]))
    if not paths:
        raise FileNotFoundError(f"No epoch checkpoints in {folder}")
    payloads = []
    for path in paths:
        _model, payload = load_mlp(path)
        payload["path"] = str(path)
        payloads.append(payload)
    return payloads


def monthly_prices(cfg: dict[str, Any], ticker: str, end: pd.Timestamp, months: int = 18) -> pd.Series:
    """Month-end adjusted closes up to ``end`` for one cached ticker."""
    path = Path(cfg["data"]["cache_dir"]) / "prices" / f"{ticker.replace('/', '-')}.parquet"
    if not path.exists():
        return pd.Series(dtype=float)
    frame = pd.read_parquet(path)
    close = frame["close"].copy()
    index = pd.DatetimeIndex(pd.to_datetime(close.index))
    if index.tz is not None:
        index = index.tz_convert("UTC").tz_localize(None)
    close.index = index
    close = close.loc[: pd.Timestamp(end)].dropna()
    monthly = close.resample("ME").last().dropna()
    return monthly.iloc[-months:]


def explainer_cross_section(cfg: dict[str, Any], date: pd.Timestamp | None = None) -> dict[str, Any]:
    """One test month: activations, three decile names, and liquid price histories."""
    stamp = pd.Timestamp(date) if date is not None else choose_explainer_date(cfg)
    blob = load_activation(cfg, stamp)
    tickers = np.asarray(blob["tickers"]).astype(str)
    scores = np.asarray(blob["ensemble_outputs"], dtype=float)
    frame = pd.DataFrame({"ticker": tickers, "score": scores})
    try:
        from xsnn.backtest import assign_deciles

        frame["decile"] = assign_deciles(frame["score"], 10).to_numpy()
    except ValueError:
        ranks = frame["score"].rank(pct=True)
        frame["decile"] = np.ceil(ranks * 10).clip(1, 10).astype(int)
    picks = []
    for decile in (10, 5, 1):
        bucket = frame.loc[frame["decile"] == decile]
        if bucket.empty:
            continue
        median_score = float(bucket["score"].median())
        chosen = bucket.iloc[(bucket["score"] - median_score).abs().argmin()]
        picks.append(chosen)
    meta = window_meta(cfg, stamp)
    return {
        "date": stamp,
        "activation": blob,
        "picks": picks,
        "window_id": meta.get("window_id", f"{stamp.year:04d}-01"),
        "meta": meta,
    }
